// Prepare chart assets for PNG export from a file:// page.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const assets = {};
for (const folder of ['assets/doctrine', 'assets/perks']) {
    for (const name of fs.readdirSync(path.join(root, folder))) {
        const mime = name.endsWith('.svg') ? 'image/svg+xml' : name.endsWith('.png') ? 'image/png' : null;
        if (!mime) continue;
        assets[`${folder}/${name}`] = `data:${mime};base64,${fs.readFileSync(path.join(root, folder, name)).toString('base64')}`;
    }
}
const payload = { assets, css: fs.readFileSync(path.join(root, 'doctrine-chart.css'), 'utf8') };
fs.writeFileSync(path.join(__dirname, 'doctrine-export-local.js'),
    '// Generated by node data/update-doctrine-export-local.cjs.\n' +
    `window.doctrineExportLocal = ${JSON.stringify(payload)};\n`);
